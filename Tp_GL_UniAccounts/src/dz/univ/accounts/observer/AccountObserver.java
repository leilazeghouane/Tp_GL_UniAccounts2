package dz.univ.accounts.observer;

/**
 * ============================================================================
 * Design Pattern: Observer (نمط المراقب - سلوكي Behavioral)
 * Role: واجهة للمشتركين / المراقبين الذين يتم إشعارهم بكل تغيير يطرأ على الحساب.
 * 
 * المشكلة التي يحلها:
 * كلما حدث شيء للحساب (إنشاء، تفعيل، تعليق، غلق، استيراد) يجب أن يعلم به عدة أطراف.
 * بدون هذا النمط، سيصبح صنف الحساب أو المستودع مرتبطاً بشدة (Tightly Coupled)
 * بأنظمة البريد وسجلات التدقيق ولوحة التحكم، مما يمنع إضافة مراقبين جدد مستقبلاً.
 * ============================================================================
 */
public interface AccountObserver {
    void onAccountEvent(AccountEvent event);
}
