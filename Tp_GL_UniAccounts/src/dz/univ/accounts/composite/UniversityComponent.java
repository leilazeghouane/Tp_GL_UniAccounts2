package dz.univ.accounts.composite;

/**
 * ============================================================================
 * Design Pattern: Composite (نمط التركيب - بنائي Structural)
 * Role: واجهة موحدة للعقد الفردية (الأوراق Leaf) والعقد المركبة (Composite).
 * 
 * المشكلة التي يحلها:
 * الجامعة بنية شجرية هرمية:
 * الجامعة -> الكليات -> الأقسام -> الأفواج -> حسابات الطلبة.
 * نريد معاملة العقدة الفردية (الطالب) والعقدة المركبة (الفوج، القسم، الكلية، الجامعة)
 * بنفس الطريقة، وخاصة الإجابة عن سؤال: "كم حساباً تحتوي هذه العقدة؟".
 * 
 * ماذا يحدث لو لم نستعمله؟
 * سنضطر لكتابة دوال وحلقات تكرارية مختلفة لكل مستوى تنظيمي (فوج، قسم، كلية)،
 * وصعوبة في حساب المجاميع التراكمية والتوسع إذا أضيفت مستويات جديدة (مثل معاهد أو مخابر).
 * ============================================================================
 */
public interface UniversityComponent {
    
    /**
     * اسم العقدة في الهيكل الجامعي
     */
    String getName();

    /**
     * حساب عدد الحسابات الموجودة تحت هذه العقدة (سؤال المشروع الأساسي)
     */
    int countAccounts();

    /**
     * طباعة الهيكل التنظيمي الشجري مع إزاحة جمالية
     */
    void printHierarchy(String indent);
}
