package dz.univ.accounts.strategy;

import dz.univ.accounts.model.StudentAccount;
import java.util.List;

/**
 * ============================================================================
 * Design Pattern: Strategy (نمط الاستراتيجية - سلوكي Behavioral)
 * Role: واجهة موحدة لخوارزميات تصدير الحسابات بصيغ متعددة (CSV, JSON, إلخ).
 * 
 * المشكلة التي يحلها:
 * نحتاج تصدير بيانات الحسابات بصيغ مختلفة، وقد تطلب الإدارة مستقبلاً صيغاً أخرى
 * مثل XML أو Excel أو PDF. بدون هذا النمط، سنضع دوالاً متداخلة وشروطاً في صنف المستودع
 * مما ينتهك مبدأ المسؤولية الفردية (SRP) ومبدأ الفتح/الإغلاق (OCP).
 * 
 * ماذا يحدث لو لم نستعمله؟
 * تشابك كود التصدير مع منطق العمل، وصعوبة تبديل صيغة التصدير ديناميكياً أثناء التشغيل.
 * ============================================================================
 */
public interface ExportStrategy {
    
    /**
     * تصدير قائمة الحسابات كـ String منسق بالصيغة المطلوبة
     */
    String export(List<StudentAccount> accounts);

    /**
     * اسم الصيغة (CSV, JSON, إلخ)
     */
    String getFormatName();
}
